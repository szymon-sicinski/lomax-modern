def test_run_slice_reports_real_semantics(tmp_path: Path) -> None:
    """The slice digest names the real spawn, collectable count and exit."""
    world = _world(
        20,
        15,
        [
            (0, 20, 30, 0x0000, (1,), None),  # Start
            (1, 40, 30, 0x0000, (1,), None),  # Exit
            (2, 60, 30, 0x0000, (1,), None),  # Moneybag
            (2, 80, 30, 0x0000, (1,), None),  # Moneybag
        ],
        nmy_names=("Start", "Exit", "Moneybag"),
    )
    path = tmp_path / "test.WLD"
    path.write_bytes(world)

    report, _ = run_slice(tmp_path, world_path=path, max_ticks=1)
    text = report.format()

    assert report.spawn_name == "Start"
    assert report.collected_total == 2
    assert report.exits == ((40, 30),)
    assert "spawn: Start (20, 30) px" in text
    assert "collect: 2 Moneybag(s)" in text
    assert "exit: Exit (40, 30) px" in text
    assert "placeholder" not in text
    assert "does not consume" not in text


def test_run_slice_reports_multiple_exits(tmp_path: Path) -> None:
    """More than one ``Exit`` placement is counted, not silently dropped."""
    world = _world(
        20,
        15,
        [
            (0, 10, 10, 0x0000, (1,), None),  # Start
            (1, 40, 30, 0x0000, (1,), None),  # Exit
            (1, 60, 50, 0x0000, (1,), None),  # Exit
        ],
        nmy_names=("Start", "Exit", "Moneybag"),
    )
    path = tmp_path / "test.WLD"
    path.write_bytes(world)

    report, _ = run_slice(tmp_path, world_path=path, max_ticks=1)
    assert report.exits == ((40, 30), (60, 50))
    assert "exit: Exit (40, 30) px (+1 more Exit placement(s))" in report.format()
