"""GNMY → Level semantics: spawn/collectables/exits and their engine wiring.

P2: ``Level.spawn`` / ``Level.collectables`` / ``Level.exits`` resolve the
playfield plane's ``GNMY`` placements to their Q32 **[V]** roles
(``Start``/``Moneybag``/``Exit``, matched on the ``NMY`` record's four-byte
name prefix), and ``new_game_state``/``run_slice`` consume them so the slice
reports the real spawn, collectable count and exit instead of placeholders.
The collect/exit logic in ``state.py`` keys off ``Entities.collectibles`` /
``Entities.exits`` and is unchanged here.  Every fixture is generated by
:mod:`tests.fixtures.synth` — no game bytes.
"""

from __future__ import annotations

from pathlib import Path

from lomax_modern.engine import (
    Collectible,
    Exit,
    Input,
    load_level,
    new_game_state,
    run_slice,
)
from lomax_modern.engine.state import _feet
from tests.fixtures.synth import (
    build_container,
    cell_payload,
    gnmy_entries_payload,
    head_payload,
    map_payload,
    nmy_payload,
    ttab_payload,
)

#: One ``GNMY`` entry in the recovered layout: (type, x, y, flags, params, extra).
#: ``W_A`` in ``nmy_payload`` is ``0x0010``, so ``K = 1`` and ``params`` is a
#: 1-tuple.
Entry = tuple[int, int, int, int, tuple[int, ...], int | None]


def _world(
    width_cells: int,
    height_cells: int,
    entries: list[Entry],
    *,
    nmy_names: tuple[str, ...],
) -> bytes:
    """One plane with an all-passable MAP, an ``NMY`` table and a ``GNMY`` chunk."""
    width_units = width_cells * 2
    height_units = height_cells * 2
    map_cells = [(0, 0)] * (width_cells * height_cells)
    chunks = [
        ("WRLD", b"PS-X" + b"\0" * 4),
        ("NMY", nmy_payload([(name, 0) for name in nmy_names], trailer=2)),
        ("PARA", b"\0" * 8),
        ("HEAD", head_payload(width_units, height_units)),
        ("TTAB", ttab_payload([[0, 0, 0, 0, 0, 0, 0, 0]])),
        ("MAP", map_payload(width_units, height_units, cells=map_cells)),
        ("GNMY", gnmy_entries_payload(entries)),
        ("MACR", b"\0" * 8),
        ("PAGE", b"\0" * 8),
        ("CELL", cell_payload([bytes(64)])),
        ("ANIM", b"\0" * 20),
        ("END", b""),
    ]
    return build_container(chunks, endian=">")


def _load(tmp_path: Path, data: bytes):
    path = tmp_path / "test.WLD"
    path.write_bytes(data)
    return load_level(path)


# ---------------------------------------------------------------------------
# Level property resolution
# ---------------------------------------------------------------------------


def test_level_resolves_spawn_collectables_and_exits(tmp_path: Path) -> None:
    """Start/Moneybag/Exit placements resolve to their pixel positions."""
    level = _load(
        tmp_path,
        _world(
            20,
            15,
            [
                (0, 10, 20, 0x0000, (1,), None),  # Start
                (1, 70, 80, 0x0000, (1,), None),  # Exit
                (2, 30, 40, 0x0000, (1,), None),  # Moneybag
                (2, 50, 60, 0x0000, (1,), None),  # Moneybag
                (3, 90, 100, 0x0000, (1,), None),  # Spikes -> other
            ],
            nmy_names=("Start", "Exit", "Moneybag", "Spikes"),
        ),
    )
    assert level.spawn == (10, 20)
    assert level.collectables == ((30, 40), (50, 60))
    assert level.exits == ((70, 80),)


def test_level_spawn_is_none_without_start(tmp_path: Path) -> None:
    """A plane with no ``Start`` placement reports ``spawn is None``."""
    level = _load(
        tmp_path,
        _world(
            20,
            15,
            [(2, 30, 40, 0x0000, (1,), None)],
            nmy_names=("Pots", "Spikes", "Moneybag"),
        ),
    )
    assert level.spawn is None
    assert level.collectables == ((30, 40),)
    assert level.exits == ()


def test_level_semantics_empty_without_nmy(tmp_path: Path) -> None:
    """A synthetic level with no ``NMY`` names resolves nothing (all empty)."""
    level = _load(
        tmp_path,
        _world(8, 4, [(0, 16, 16, 0x0000, (1,), None)], nmy_names=()),
    )
    # No NMY records → decode_gnmy fails (k_of empty) → the plane has no entries.
    assert level.gnmy == ()
    assert level.spawn is None
    assert level.collectables == ()
    assert level.exits == ()


