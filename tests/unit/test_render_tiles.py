"""Tile-art composition (MAP -> TTAB -> CELL -> HEAD palette) over synthetic data.

``engine.render_tiles`` walks the visible ``MAP`` cells and blits each resolved
``TTAB`` record as its four ``CELL`` blocks.  Everything here is generated by
``tests.fixtures.synth`` — no game bytes.  What is graded:

* the HEAD palette (slot 1) is used, so a 15-bit red palette word paints the
  exact ``B5G6R5`` word ``0xF800``;
* index 0 is transparent: the key *colour* never appears and the backdrop shows
  through;
* a ``FLIP_H`` flag mirrors a corner pixel to the opposite column;
* a ``tile_word`` outside the plane's ``TTAB`` bank leaves the backdrop instead
  of crashing or inventing art;
* the player marker is overlaid and the camera scrolls the *tile art*, not just
  the marker.
"""

from __future__ import annotations

from pathlib import Path

from lomax_modern import art
from lomax_modern.engine import (
    CELL_PX,
    camera,
    load_level,
    new_game_state,
    render_tiles,
    run_slice,
)
from lomax_modern.engine.render import COLOUR_PLAYER, COLOUR_SKY
from tests.fixtures.synth import (
    build_container,
    cell_payload,
    gnmy_payload,
    head_payload,
    map_payload,
    ttab_payload,
)

#: 15-bit HEAD palette words and their ``B5G6R5`` forms after widening.
RED15, RED565 = 0x7C00, 0xF800
BLUE15, BLUE565 = 0x001F, 0x001F
MAGENTA15, MAGENTA565 = 0x7C1F, 0xF81F


def _palette(index_colours: dict[int, int]) -> list[int]:
    """256 15-bit words; index 0 stays 0 (the transparent key colour)."""
    words = [0] * 256
    for index, word in index_colours.items():
        words[index] = word
    return words


def _world(
    width_cells: int,
    height_cells: int,
    *,
    cells: list[bytes],
    records: list[list[int]],
    map_overrides: dict[tuple[int, int], tuple[int, int]] | None = None,
    map_default: int = 0,
    palette_slot1: dict[int, int] | None = None,
) -> bytes:
    """One plane whose MAP cell (x, y) -> (tile_word, collision), row-major."""
    width_units = width_cells * 2
    height_units = height_cells * 2
    overrides = map_overrides or {}
    map_cells = [
        overrides.get((x, y), (map_default, 0))
        for y in range(height_cells)
        for x in range(width_cells)
    ]
    palettes = None
    if palette_slot1 is not None:
        palettes = [[0] * 256, _palette(palette_slot1)]
    chunks = [
        ("WRLD", b"PS-X" + b"\0" * 4),
        ("NMY", b"\0" * 16),
        ("PARA", b"\0" * 8),
        ("HEAD", head_payload(width_units, height_units, palettes=palettes)),
        ("TTAB", ttab_payload(records)),
        ("MAP", map_payload(width_units, height_units, cells=map_cells)),
        ("GNMY", gnmy_payload((0,))),
        ("MACR", b"\0" * 8),
        ("PAGE", b"\0" * 8),
        ("CELL", cell_payload(cells)),
        ("ANIM", b"\0" * 20),
        ("END", b""),
    ]
    return build_container(chunks, endian=">")


def _load(tmp_path: Path, data: bytes):
    path = tmp_path / "test.WLD"
    path.write_bytes(data)
    return load_level(path)


#: A solid red 8x8 CELL: every pixel is palette index 1.
RED_CELL = bytes([1] * 64)
#: A solid blue 8x8 CELL: every pixel is palette index 2.
BLUE_CELL = bytes([2] * 64)
#: An empty 8x8 CELL: every pixel is index 0 (transparent).
EMPTY_CELL = bytes(64)
#: A corner 8x8 CELL: palette index 1 at (0, 0), transparent elsewhere.
CORNER_CELL = bytes([1] + [0] * 63)

#: A TTAB record whose four slots all name CELL 0, no flags.
RED_TILE = [0, 0, 0, 0, 0, 0, 0, 0]
#: A TTAB record whose four slots all name CELL 1 (blue), no flags.
BLUE_TILE = [1, 0, 1, 0, 1, 0, 1, 0]
#: A TTAB record whose four slots name the empty CELL, no flags.
EMPTY_TILE = [1, 0, 1, 0, 1, 0, 1, 0]


def test_render_tiles_composes_art_with_the_head_palette(tmp_path: Path) -> None:
    """A red CELL, referenced by a tile the MAP names, paints 0xF800 at scale."""
    world = _world(
        4,
        4,
        cells=[RED_CELL],
        records=[RED_TILE],
        map_default=0,
        palette_slot1={1: RED15},
    )
    level = _load(tmp_path, world)
    state = new_game_state(level, spawn_x=0.0, spawn_y=0.0)
    frame = render_tiles(level, state)

    # Tile art: the whole 64x64 playfield is the red tile...
    assert frame.pixel(24, 24) == RED565
    assert frame.pixel(63, 63) == RED565
    # ...the player marker is overlaid at the spawn...
    assert frame.pixel(0, 0) == COLOUR_PLAYER
    # ...and pixels past the playfield edge stay the backdrop.
    assert frame.pixel(64, 0) == COLOUR_SKY
    assert frame.width == 320 and frame.height == 240


def test_render_tiles_index0_is_transparent(tmp_path: Path) -> None:
    """The transparent key colour never paints; the backdrop shows through."""
    world = _world(
        4,
        4,
        cells=[EMPTY_CELL],
        records=[RED_TILE],
        map_default=0,
        palette_slot1={0: MAGENTA15},
    )
    level = _load(tmp_path, world)
    state = new_game_state(level, spawn_x=0.0, spawn_y=0.0)
    frame = render_tiles(level, state)

    assert frame.pixel(24, 24) == COLOUR_SKY
    assert MAGENTA565 not in frame.pixels


def test_render_tiles_honours_flip_flags(tmp_path: Path) -> None:
    """A FLIP_H slot mirrors a corner pixel to the opposite column."""
    world = _world(
        4,
        4,
        cells=[CORNER_CELL, EMPTY_CELL],
        records=[
            [0, art.FLIP_H, 1, 0, 1, 0, 1, 0],  # tile 0: slot 0 H-flipped
            EMPTY_TILE,  # tile 1: empty
        ],
        map_overrides={(0, 0): (0, 0)},
        map_default=1,
        palette_slot1={1: RED15},
    )
    level = _load(tmp_path, world)
    state = new_game_state(level, spawn_x=48.0, spawn_y=48.0)
    frame = render_tiles(level, state)

    # Tile 0 sits at screen (0, 0); its H-flipped corner pixel lands at column 7.
    assert frame.pixel(7, 0) == RED565
    assert frame.pixel(0, 0) == COLOUR_SKY


def test_render_tiles_out_of_bank_tile_word_is_backdrop(tmp_path: Path) -> None:
    """A MAP word outside the TTAB bank is skipped, never repaired."""
    world = _world(
        4,
        4,
        cells=[RED_CELL],
        records=[RED_TILE],
        map_overrides={(0, 0): (99, 0)},
        map_default=0,
        palette_slot1={1: RED15},
    )
    level = _load(tmp_path, world)
    state = new_game_state(level, spawn_x=48.0, spawn_y=48.0)
    frame = render_tiles(level, state)

    assert frame.pixel(1, 1) == COLOUR_SKY  # out-of-bank tile word
    assert frame.pixel(17, 17) == RED565  # in-bank neighbour still paints


def test_render_tiles_scrolls_the_tile_art_with_the_camera(tmp_path: Path) -> None:
    """Moving the player right scrolls a distant blue tile into view."""
    width_cells, height_cells = 40, 20
    world = _world(
        width_cells,
        height_cells,
        cells=[RED_CELL, BLUE_CELL],
        records=[RED_TILE, BLUE_TILE],
        map_overrides={(30, 5): (1, 0)},
        map_default=0,
        palette_slot1={1: RED15, 2: BLUE15},
    )
    level = _load(tmp_path, world)
    assert level.width_px == 40 * CELL_PX  # 640 px, two 320 px screens

    at_spawn = new_game_state(level, spawn_x=0.0, spawn_y=0.0)
    frame_a = render_tiles(level, at_spawn)
    assert camera(level, at_spawn.player, 320, 240)[0] == 0
    # The blue tile is at cell (30, 5) -> screen x = 480, off the 320-px view.
    assert BLUE565 not in frame_a.pixels

    moved = new_game_state(level, spawn_x=0.0, spawn_y=0.0)
    moved.player.x = 400.0
    cam_x, _ = camera(level, moved.player, 320, 240)
    frame_b = render_tiles(level, moved)
    assert cam_x > 0
    assert frame_b.pixel(30 * CELL_PX - cam_x, 5 * CELL_PX) == BLUE565
    assert frame_a.pixels != frame_b.pixels


def test_run_slice_on_frame_emits_tile_art_not_the_grid(tmp_path: Path) -> None:
    """The ``on_frame`` sink now receives composed tile art."""
    game_dir = tmp_path / "game"
    (game_dir / "WORLDS").mkdir(parents=True)
    world = _world(
        4,
        4,
        cells=[RED_CELL],
        records=[RED_TILE],
        map_default=0,
        palette_slot1={1: RED15},
    )
    (game_dir / "WORLDS" / "VILLAGE.WLD").write_bytes(world)

    captured = []
    report, final = run_slice(
        str(game_dir), max_ticks=3, on_frame=lambda i, frame: captured.append(frame)
    )

    assert report.frames == 3
    assert len(captured) == 3
    assert all(frame.pixel(24, 24) == RED565 for frame in captured)
    assert final.pixel(24, 24) == RED565
