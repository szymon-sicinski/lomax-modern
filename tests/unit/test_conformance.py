ROOT = Path(__file__).resolve().parents[2]


# -- the 16-bit -> 8-bit expansion (the bug this harness found) ------------


def test_rgb565_to_rgb8_replicates_every_channel_to_eight_bits() -> None:
    """6-bit green must widen by bit replication, not by a shift and a nibble."""
    assert rgb565_to_rgb8(0x0000) == (0, 0, 0)
    assert rgb565_to_rgb8(0xFFFF) == (255, 255, 255)
    assert rgb565_to_rgb8(0xF800) == (255, 0, 0)
    assert rgb565_to_rgb8(0x001F) == (0, 0, 255)
    assert rgb565_to_rgb8(0x07E0) == (0, 255, 0)
    # Mid-range greens: g6=4 -> 16, g6=8 -> 32, g6=45 -> 182 (not 191).
    assert rgb565_to_rgb8(4 << 5) == (0, 16, 0)
    assert rgb565_to_rgb8(8 << 5) == (0, 32, 0)
    assert rgb565_to_rgb8(45 << 5) == (0, 182, 0)


def test_to_rgba_expands_green_with_replication() -> None:
    fb = renderer.Framebuffer(2, 1)
    fb.set(0, 0, 45 << 5)  # g6 == 45 -> 182/255, not 191/255
    fb.set(1, 0, 0x07E0)  # pure green
    assert fb.to_rgba() == bytes((0, 182, 0, 255, 0, 255, 0, 255))


# -- the measured depth tolerance ------------------------------------------


def test_depth_tolerance_is_measured_over_every_15_bit_word() -> None:
    """Red and blue pass through 5 bits on both paths; green costs <= 2/255."""
    assert depth_tolerance() == (0, 2, 0)


def test_depth_tolerance_is_the_worst_case_of_the_real_code_paths() -> None:
    """Re-derive the bound independently: the constant must not be a guess."""
    worst = [0, 0, 0]
    for word in range(0x8000):
        direct = art.rgb15_to_rgb8(word)
        via = rgb565_to_rgb8(rgb15_to_rgb565(word))
        for channel, (a, b) in enumerate(zip(direct, via)):
            worst[channel] = max(worst[channel], abs(a - b))
    assert tuple(worst) == depth_tolerance()


# -- depth 16 vs 24 on every fixture --------------------------------------


@pytest.mark.parametrize("scene", scenes(), ids=lambda scene: scene.name)
def test_depth_16_conforms_to_depth_24(scene: Scene) -> None:
    report = check_depth(scene)
    assert report.ok, report.detail()
    assert report.mismatch_count == 0
    assert all(
        delta <= bound for delta, bound in zip(report.max_delta, report.tolerance)
    )


def test_depth_16_and_24_frames_differ_in_representation_not_structure() -> None:
    """Every pixel is coloured in both frames: the comparison is never on zeros."""
    scene = scenes()[0]
    frame16 = render(scene, Depth.BPP16)
    frame24 = render(scene, Depth.BPP24)
    assert frame16.pixels != frame24.pixels
    assert len(set(frame16.pixels)) > 3
    assert len(set(frame24.pixels)) > 3
    assert frame16.to_bytes() == b"".join(
        word.to_bytes(2, "little") for word in frame16.pixels
    )
    assert len(frame24.to_bytes()) == 3 * frame24.width * frame24.height


def _broken_green(scene: Scene, depth: Depth, **_: int) -> Frame:
    """A renderer with the old 6->8 green expansion: the harness must reject it.

    Named for what it does — the old formula *over*-brightens most mid tones
    (+12/255 at g=60), so "truncated" was the wrong verb.
    """
    frame = render(scene, depth)
    if depth is Depth.BPP16:
        broken = []
        for word in frame.pixels:
            red = (word >> 11) & 0x1F
            green = (word >> 5) & 0x3F
            blue = word & 0x1F
            green_broken = min(63, green + 1)  # one 6-bit step too bright
            broken.append((red << 11) | (green_broken << 5) | blue)
        return Frame(Depth.BPP16, frame.width, frame.height, tuple(broken))
    return frame


def test_depth_check_rejects_a_broken_green_channel() -> None:
    report = check_depth(scenes()[0], render_fn=_broken_green)
    assert not report.ok
    assert report.mismatch_count > 0
    assert report.mismatches[0].delta[1] > report.tolerance[1]


def _offset_sprites(scene: Scene, depth: Depth, **kwargs: int) -> Frame:
    """A renderer that places sprites one pixel off at depth 24 only."""
    if depth is Depth.BPP24 and scene.sprites:
        shifted = Scene(
            name=scene.name,
            width=scene.width,
            height=scene.height,
            background=scene.background,
            palette=scene.palette,
            sprites=tuple(
                Sprite(sprite.cell, sprite.x + 1, sprite.y) for sprite in scene.sprites
            ),
            tiles=scene.tiles,
        )
        return render(shifted, depth, **kwargs)
    return render(scene, depth, **kwargs)


def test_depth_check_rejects_a_placement_divergence() -> None:
    """The 24-bit reference places cells itself, so a 1-px offset cannot hide."""
    scene = Scene(
        name="offset",
        width=16,
        height=16,
        background=0x2108,
        palette=synthetic_palette(),
        sprites=(Sprite(pattern_cell(0, 3), 4, 4),),
    )
    assert check_depth(scene).ok
    report = check_depth(scene, render_fn=_offset_sprites)
    assert not report.ok
    assert report.mismatch_count > 0


# -- transparency ---------------------------------------------------------


@pytest.mark.parametrize("scene", scenes(), ids=lambda scene: scene.name)
def test_transparency_never_paints_the_key_colour(scene: Scene) -> None:
    report = check_transparency(scene)
    assert report.ok, report.detail()
    assert report.transparent_pixels > 0
    assert report.altered_pixels == 0
    assert report.key_leaks_16 == 0
    assert report.key_leaks_24 == 0
    assert report.untouched_pixels + report.occluded_pixels == report.transparent_pixels


def _leaking_blit(scene: Scene, depth: Depth, **kwargs: int) -> Frame:
    """Frame where index-0 pixels were painted with the palette's key word."""
    frame = render(scene, depth)
    if depth is Depth.BPP24:
        return frame
    key = rgb15_to_rgb565(scene.palette[renderer.TRANSPARENT_INDEX])
    pixels = list(frame.pixels)
    for cell, x0, y0 in (
        (sprite.cell, sprite.x, sprite.y) for sprite in scene.sprites
    ):
        for y in range(8):
            for x in range(8):
                if cell.pixels[y * 8 + x] == renderer.TRANSPARENT_INDEX:
                    px, py = x0 + x, y0 + y
                    if 0 <= px < frame.width and 0 <= py < frame.height:
                        pixels[py * frame.width + px] = key
    return Frame(Depth.BPP16, frame.width, frame.height, tuple(pixels))


def test_transparency_check_rejects_a_key_colour_leak() -> None:
    scene = Scene(
        name="leak",
        width=16,
        height=16,
        background=0x2108,
        palette=synthetic_palette(),
        sprites=(Sprite(pattern_cell(0, 5), 2, 2),),
    )
    assert check_transparency(scene).ok
    report = check_transparency(scene, render_fn=_leaking_blit)
    assert not report.ok
    assert report.altered_pixels > 0
    assert report.key_leaks_16 > 0


def test_a_fixture_with_an_ambiguous_key_colour_is_rejected() -> None:
    palette = list(synthetic_palette())
    palette[7] = palette[0]
    with pytest.raises(ValueError, match="transparent key colour"):
        Scene(
            name="ambiguous",
            width=16,
            height=16,
            background=0x2108,
            palette=tuple(palette),
        )
    with pytest.raises(ValueError, match="background equals"):
        Scene(
            name="ambient",
            width=16,
            height=16,
            background=palette[0],
            palette=tuple(synthetic_palette()),
        )


# -- integer scale / no shimmer -------------------------------------------


@pytest.mark.parametrize(("factor", "index"), [(3, 0), (2, 2)])
def test_integer_scale_is_uniform_blocks_and_rigid_scroll(factor: int, index: int) -> None:
    report = check_integer_scale(scenes()[index], factor)
    assert report.ok, report.detail()
    assert report.applied_scale == factor
    assert report.blocks.violations == 0
    assert report.shift_violations == 0
    assert report.content[0] % factor == 0 and report.content[1] % factor == 0


def test_integer_scale_pads_are_exact_and_centred() -> None:
    scene = scenes()[0]
    report = check_integer_scale(scene, 3, surface=(scene.width * 3 + 2, scene.height * 3 + 4))
    left, right, top, bottom = report.pads
    assert (left, right) == (1, 1)
    assert (top, bottom) == (2, 2)
    assert report.content[0] + left + right == report.surface[0]
    assert report.content[1] + top + bottom == report.surface[1]


def test_block_checker_rejects_a_fractional_scale() -> None:
    """A 2.5x presentation duplicates uneven columns — exactly the shimmer case."""
    scene = scenes()[0]
    source = render(scene, Depth.BPP16)
    image = source.to_image()

    width = int(scene.width * 2.5)
    height = int(scene.height * 2.5)

    def fractional() -> tuple[int, ...]:
        # Sample at 2.5 px per source pixel: some source pixels get 2 output
        # columns, some 3 — a factor that does not exist as an integer.
        out = []
        for y in range(height):
            sy = min(image.height - 1, int(y / 2.5))
            for x in range(width):
                sx = min(image.width - 1, int(x / 2.5))
                out.append(image.at(sx, sy))
        return tuple(out)

    report = check_block_replication(source, fractional(), (width, height), 2)
    assert not report.ok
    assert report.violations > 0


def test_scroll_checker_rejects_a_resampled_shift() -> None:
    """A 1-px scroll that lands one output pixel off must be reported."""
    scene = scenes()[0]
    factor = 3
    surface = (scene.width * factor, scene.height * factor)
    base = present(render(scene, Depth.BPP16).to_image(), *surface, filter=Filter.NEAREST)
    shifted = present(
        render(scene, Depth.BPP16, scroll_x=1).to_image(), *surface, filter=Filter.NEAREST
    )
    content = (base.scaled.width, base.scaled.height)
    assert (
        check_scroll_shift(
            base.surface.pixels,
            shifted.surface.pixels,
            surface,
            factor=factor,
            shift_px=1,
            content=content,
        )
        == 0
    )
    one_pixel_off = list(shifted.surface.pixels)
    tampered = content[0] // 2
    # The invariant under test is shifted(x) == base(x + factor), so break exactly
    # one of those comparisons with a value that cannot accidentally match.
    one_pixel_off[tampered] = (base.surface.pixels[tampered + factor] + 1) & 0xFFFF
    assert (
        check_scroll_shift(
            base.surface.pixels,
            tuple(one_pixel_off),
            surface,
            factor=factor,
            shift_px=1,
            content=content,
        )
        > 0
    )


def test_fit_never_uses_a_fractional_factor() -> None:
    awkward = check_integer_fit((320, 240), (800, 600))
    assert awkward.ok
    assert awkward.ideal_ratio == pytest.approx(2.5)
    assert awkward.applied_scale == 2
    assert awkward.content == (640, 480)
    assert awkward.pads == (80, 80, 60, 60)

    modern = check_integer_fit((320, 240), (1920, 1080))
    assert modern.applied_scale == 4
    assert modern.content == (1280, 960)
    assert modern.pads == (320, 320, 60, 60)


def test_nearest_presentation_equals_the_scaler_block_replication() -> None:
    """The block check agrees with the scaler's own nearest() on the same frame."""
    scene = scenes()[2]
    frame = render(scene, Depth.BPP16)
    scaled = nearest(frame.to_image(), 2)
    assert scaled.width == scene.width * 2
    report = check_block_replication(frame, scaled.pixels, (scaled.width, scaled.height), 2)
    assert report.ok


# -- out-of-bank cells stay empty (Q22 preserved) -------------------------


def test_out_of_bank_cell_index_is_skipped_in_both_depths() -> None:
    """The fourth cell of the strip tile indexes outside the bank: leave it empty."""
    scene = scenes()[0]
    frame16 = render(scene, Depth.BPP16)
    frame24 = render(scene, Depth.BPP24)
    tile = scene.tiles[-1]
    assert tile.record.cell_indices[-1] >= len(tile.cells)
    x0 = tile.x + 3 * 8
    for y in range(tile.y, tile.y + 8):
        for x in range(x0, x0 + 8):
            assert frame16.pixel(x, y) == rgb15_to_rgb565(scene.background)
            assert frame24.pixel(x, y) == (
                (scene.background_rgb[0] << 16)
                | (scene.background_rgb[1] << 8)
                | scene.background_rgb[2]
            )


# -- the harness as a whole ----------------------------------------------


def test_harness_run_is_green_and_names_every_case() -> None:
    result = run()
    assert result.ok, result.summary()
    names = [case.name for case in result.cases]
    assert len(names) == len(set(names))
    assert any(name.startswith("depth-16-vs-24/") for name in names)
    assert any(name.startswith("transparency/") for name in names)
    assert any(name.startswith("integer-scale/") for name in names)
    assert "integer-fit/320x240-in-800x600" in names
    assert "verdict: PASS" in result.summary()


def test_harness_run_reports_failure_when_a_case_fails() -> None:
    result = run(render_fn=_broken_green)
    assert not result.ok
    assert result.failures
    assert "verdict: FAIL" in result.summary()


def test_cli_prints_a_report_and_exits_zero(capsys: pytest.CaptureFixture[str]) -> None:
    assert main([]) == 0
    out = capsys.readouterr().out
    assert "render conformance" in out
    assert "verdict: PASS" in out
    assert "display: not required" in out


def test_cli_writes_json_and_rejects_unknown_arguments(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / "conformance.json"
    assert main(["--json", str(target)]) == 0
    payload = json.loads(target.read_text(encoding="utf-8"))
    assert payload["ok"] is True
    assert payload["display"] == "not required"
    assert payload["depth_tolerance"] == list(depth_tolerance())
    assert all(case["ok"] for case in payload["cases"])
    assert main(["--nope"]) == 2
    assert main(["--help"]) == 0


def test_harness_runs_headless_without_a_display() -> None:
    """CI has no X server: the harness must render offscreen and still pass."""
    env = {key: value for key, value in os.environ.items() if key != "DISPLAY"}
    env["PYTHONPATH"] = str(ROOT / "src")
    completed = subprocess.run(
        [sys.executable, "-m", "lomax_modern.conformance"],
        cwd=ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert completed.returncode == 0, completed.stderr
    assert "verdict: PASS" in completed.stdout
    assert "display: not required (DISPLAY=unset)" in completed.stdout


# -- frame / comparison API guards ---------------------------------------


def test_frame_rejects_bad_geometry_and_out_of_depth_pixels() -> None:
    with pytest.raises(ValueError, match="positive"):
        Frame(Depth.BPP16, 0, 4, ())
    with pytest.raises(ValueError, match="needs 4 pixels"):
        Frame(Depth.BPP16, 2, 2, (0, 0, 0))
    with pytest.raises(ValueError, match="does not fit depth 16"):
        Frame(Depth.BPP16, 1, 1, (0x10000,))
    with pytest.raises(ValueError, match="does not fit depth 24"):
        Frame(Depth.BPP24, 1, 1, (0x1000000,))
    with pytest.raises(IndexError):
        Frame(Depth.BPP16, 1, 1, (0,)).pixel(1, 0)
    with pytest.raises(ValueError, match="depth-16 frame"):
        Frame(Depth.BPP24, 1, 1, (0,)).to_image()


def test_compare_frames_requires_one_frame_of_each_depth() -> None:
    frame = Frame(Depth.BPP16, 1, 1, (0,))
    other = Frame(Depth.BPP16, 1, 1, (0,))
    with pytest.raises(ValueError, match="depth-16 and one depth-24"):
        compare_frames(frame, other)
    wide = Frame(Depth.BPP24, 2, 1, (0, 0))
    with pytest.raises(ValueError, match="frame sizes differ"):
        compare_frames(frame, wide)


def test_scale_checks_reject_impossible_arguments() -> None:
    with pytest.raises(ValueError, match="does not fit"):
        fit_scale(4, 4, 1, 1)
    with pytest.raises(ValueError, match="factor must be >= 1"):
        check_block_replication(Frame(Depth.BPP16, 1, 1, (0,)), (0,), (1, 1), 0)
    with pytest.raises(ValueError, match="presented buffer"):
        check_block_replication(Frame(Depth.BPP16, 1, 1, (0,)), (0, 0), (1, 1), 1)
    with pytest.raises(ValueError, match="covers the whole"):
        check_scroll_shift(
            (0, 0), (0, 0), (2, 1), factor=2, shift_px=1, content=(2, 1)
        )
