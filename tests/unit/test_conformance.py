"""Tests for the headless render-conformance harness.

Synthetic fixtures only: every frame here is generated by
``lomax_modern.conformance`` from its own palettes and cells.  No game data, no
display, no ``LOMAX.EXE``.

Two things are graded, and the second matters more than the first:

* the harness passes on the real renderer (depth 16 vs 24, transparency, integer
  scale), and
* the harness **fails** when handed a broken renderer — a truncated green
  channel, a blit that paints the transparent key, a placement offset, a
  fractional-scale presentation.  A checker that cannot fail is a tautology, so
  every ``check_*`` entry point is exercised with a deliberate defect.

The depth-16 -> depth-24 green expansion is also pinned here: it was found by
this harness (`>>2` instead of `>>4` when widening 6-bit green to 8 bits, which
changes 55 of the 64 green values — over-brightens 46 by up to 12/255, under-brightens 9 by up to 3/255).
"""

from __future__ import annotations

import json
