def test_cli_export_rejects_missing_file_and_game_folder(tmp_path, capsys) -> None:
    from lomax_modern.cli import main

    assert main(["export", str(tmp_path / "nope.WLD"), "--out", str(tmp_path / "o")]) == 2
    assert "not a file" in capsys.readouterr().err

    game = tmp_path / "game"
    (game / "WORLDS").mkdir(parents=True)
    (game / "LOMAX.EXE").write_bytes(b"MZ")
    world_path = build_world_file(game / "WORLDS")
    assert main(["export", str(world_path), "--out", str(game / "art")]) == 2
    assert "refusing to write" in capsys.readouterr().err
