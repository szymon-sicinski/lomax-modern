def test_planes_pairs_each_head_with_its_ttab_and_map() -> None:
    world = World(
        chunks=[
            chunk("HEAD", head_payload(8, 4)),
            chunk("TTAB", ttab_payload([(1, 0, 2, 0, 3, 0, 4, 0)])),
            chunk("MAP", map_payload(8, 4)),
            chunk("GNMY", b"\x00" * 4),
            chunk("HEAD", head_payload(4, 2)),
            chunk(
                "TTAB",
                ttab_payload([(5, 0, 6, 0, 7, 0, 8, 0), (9, 0, 10, 0, 11, 0, 12, 0)]),
            ),
            chunk("MAP", map_payload(4, 2)),
        ]
    )
    sections = art.planes(world)

    assert len(sections) == 2
    assert sections[0].plane.cell_count == 8 and len(sections[0].tiles) == 1
    assert sections[1].plane.cell_count == 2 and len(sections[1].tiles) == 2
    assert sections[1].tiles[0].cell_indices == (5, 6, 7, 8)


