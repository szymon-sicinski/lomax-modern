def test_rgb15_expansion_covers_the_full_range() -> None:
    assert art.rgb15_to_rgb8(0x7FFF) == (255, 255, 255)
    assert art.rgb15_to_rgb8(0x0000) == (0, 0, 0)
    assert art.rgb15_to_rgb8(0x001F) == (0, 0, 255)  # blue in bits 0-4
    assert art.rgb15_to_rgb8(0x7C00) == (255, 0, 0)  # red in bits 10-14
    assert art.rgb15_to_rgb8(0x03E0) == (0, 255, 0)  # green in bits 5-9


def test_head_palette_reads_the_requested_slot_only() -> None:
    slot0 = [0x001F] * 256  # all blue
    slot1 = [0x7C00] * 256  # all red
    head_chunk = head({0: slot0, 1: slot1})

    assert art.head_palette(head_chunk, 0).rgb(7) == (0, 0, 255)
    assert art.head_palette(head_chunk, 1).rgb(7) == (255, 0, 0)
    assert art.head_palette(head_chunk).slot == art.DEFAULT_PALETTE_SLOT


def test_sprite_and_tile_palette_slots_are_distinct() -> None:
    """Sprites resolve through slot 0 and tiles through slot 1 — pinned.

    The split is the regression guard for the "green hero" defect: slot 1 maps
    the hero's body indices to an all-green ramp, so the sprite path must never
    fall back to the tile slot.
    """
    assert art.SPRITE_PALETTE_SLOT == 0
    assert art.DEFAULT_PALETTE_SLOT == 1
    assert art.SPRITE_PALETTE_SLOT != art.DEFAULT_PALETTE_SLOT


def test_head_palette_rejects_bad_slot_tag_and_short_payload() -> None:
    good = head({1: [0x7FFF] * 256})
    with pytest.raises(ArtError, match="palette slot"):
        art.head_palette(good, 10)
    with pytest.raises(ArtError, match="needs a HEAD chunk"):
        art.head_palette(chunk("CELL", b"\x00" * 64))
    with pytest.raises(ArtError, match="palette block"):
        art.head_palette(chunk("HEAD", b"\x00" * 16))


def test_palette_transparent_index_has_alpha_zero() -> None:
    # Even when palette entry 0 decodes to opaque white, index 0 stays the key.
    palette = art.head_palette(head({1: [0x7FFF] * 256}), 1)
    assert palette.rgb(0) == (255, 255, 255)
    assert palette.rgba(0) == (0, 0, 0, 0)
    assert palette.rgba(1) == (255, 255, 255, 255)
    with pytest.raises(ArtError, match="outside"):
        palette.rgb(256)


def test_palette_slots_non_empty_reports_only_populated_slots() -> None:
    head_chunk = head({0: [0x0000] * 256, 1: [0x0001] * 256, 3: [0x0002] * 256})
    assert art.palette_slots_non_empty(head_chunk) == (1, 3)


