def test_map_field_image_draws_raw_bytes_as_grey() -> None:
    cells = [(0x1200, 0x00), (0x0034, 0x80)]
    plane = art.decode_map(
        chunk("MAP", map_payload(4, 2, cells=cells)), head(width_units=4, height_units=2)
    )

    collision = art.map_field_image(plane, channel="collision")
    assert (collision.width, collision.height) == (2, 1)
    assert collision.pixels[0:4] == bytes((0, 0, 0, 0))  # 0x00 stays background
    assert collision.pixels[4:8] == bytes((128, 128, 128, 255))

    high = art.map_field_image(plane, channel="word-hi")
    assert high.pixels[0:4] == bytes((0x12, 0x12, 0x12, 255))
    low = art.map_field_image(plane, channel="word-lo")
    assert low.pixels[4:8] == bytes((0x34, 0x34, 0x34, 255))

    with pytest.raises(ArtError, match="channel"):
        art.map_field_image(plane, channel="meaning")


