def chunk(tag: str, payload: bytes, offset: int = 0) -> Chunk:
    return Chunk(
        tag=tag,
        tag_field=tag.encode("ascii").ljust(4, b" "),
        size=len(payload),
        payload=payload,
        header_offset=offset,
    )


def head(words_by_slot: dict[int, Sequence[int]] | None = None,
         width_units: int = 8, height_units: float = 4) -> Chunk:
    palettes = None
    if words_by_slot is not None:
        palettes = [[0] * 256 for _ in range(max(words_by_slot) + 1)]
        for slot, words in words_by_slot.items():
            palettes[slot] = list(words)
    return chunk("HEAD", head_payload(width_units, int(height_units), palettes=palettes))


