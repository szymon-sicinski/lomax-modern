def test_decode_map_uses_head_geometry_and_keeps_pad() -> None:
    # 8 x 4 HEAD units = 64 x 32 pixels = 4 x 2 cells = 8 cells = 24 B (no pad).
    cells = [(0x1234, 0x80), (0x0005, 0x00)] + [(0, 0)] * 6
    plane = art.decode_map(
        chunk("MAP", map_payload(8, 4, cells=cells)), head(width_units=8, height_units=4)
    )

    assert (plane.width_cells, plane.height_cells) == (4, 2)
    assert plane.cell_count == 8
    assert plane.pad == b""
    assert plane.at(0, 0) == art.MapCell(tile_word=0x1234, collision=0x80)
    assert plane.at(1, 0).tile_word == 0x0005
    assert plane.at(3, 1) == art.MapCell(tile_word=0, collision=0)


def test_decode_map_keeps_the_zero_pad_bytes() -> None:
    # 2 x 2 HEAD units = 1 cell = 3 B + 1 pad byte.
    plane = art.decode_map(
        chunk("MAP", map_payload(2, 2)), head(width_units=2, height_units=2)
    )
    assert plane.cell_count == 1
    assert plane.pad == b"\x00"


def test_decode_map_rejects_size_and_pad_mismatch() -> None:
    head_chunk = head(width_units=2, height_units=2)
    with pytest.raises(ArtError, match="expected"):
        art.decode_map(chunk("MAP", b"\x00" * 3), head_chunk)  # missing pad byte
    with pytest.raises(ArtError, match="not zero"):
        art.decode_map(chunk("MAP", b"\x00" * 3 + b"\x01"), head_chunk)
    with pytest.raises(ArtError, match="needs a MAP chunk"):
        art.decode_map(chunk("TTAB", b"\x00" * 8), head_chunk)


