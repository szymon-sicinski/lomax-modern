def test_decode_cells_keeps_each_record_verbatim() -> None:
    first = bytes(range(64))
    second = bytes((255 - i) for i in range(64))
    cells = art.decode_cells(chunk("CELL", cell_payload([first, second])))

    assert len(cells) == 2
    assert cells[0].pixels == first and cells[0].index == 0
    assert cells[1].pixels == second and cells[1].index == 1
    # Round-trip: the records concatenate back to the exact payload.
    assert b"".join(c.pixels for c in cells) == first + second


def test_cell_pixel_is_row_major() -> None:
    cell = art.decode_cells(chunk("CELL", bytes(range(64))))[0]
    assert cell.pixel(0, 0) == 0
    assert cell.pixel(1, 0) == 1
    assert cell.pixel(0, 1) == 8
    assert cell.pixel(7, 7) == 63
    with pytest.raises(ArtError, match="outside"):
        cell.pixel(8, 0)


def test_decode_cells_rejects_partial_record() -> None:
    with pytest.raises(ArtError, match="not a multiple of 64"):
        art.decode_cells(chunk("CELL", b"\x00" * 65))
    with pytest.raises(ArtError, match="needs a CELL chunk"):
        art.decode_cells(chunk("TTAB", b"\x00" * 8))


