def test_export_world_is_repeatable(tmp_path) -> None:
    world_path = build_world_file(tmp_path)
    first = art.export_world(world_path, tmp_path / "a")
    second = art.export_world(world_path, tmp_path / "b")
    assert first.lines == second.lines
    for path, other in zip(sorted(first.files), sorted(second.files)):
        assert path.read_bytes() == (tmp_path / "b" / path.name).read_bytes()


def test_export_refuses_to_write_into_the_game_folder(tmp_path) -> None:
    game = tmp_path / "game"
    worlds = game / "WORLDS"
    worlds.mkdir(parents=True)
    (game / "LOMAX.EXE").write_bytes(b"MZ")  # stands in for the retail binary
    world_path = build_world_file(worlds)

    with pytest.raises(ArtError, match="refusing to write"):
        art.export_world(world_path, game / "art")
    with pytest.raises(ArtError, match="refusing to write"):
        art.export_world(world_path, worlds / "art")
    # Anywhere outside the install is fine.
    report = art.export_world(world_path, tmp_path / "outside")
    assert report.files


