"""GNMY density-marker overlay — position + ``type_index``, no semantics.

``engine.overlay_gnmy`` draws one small marker per ``GNMY`` placement at its
pixel ``(x, y)``, coloured by ``type_index``.  What a placement *means*
(spawn/collectable/exit) is Q32 unresolved and is never attached here.  Every
fixture is generated by :mod:`tests.fixtures.synth` — no game bytes.
"""

from __future__ import annotations

from pathlib import Path

from lomax_modern.anim_nmy import GnmyEntry
from lomax_modern.engine import (
    CELL_PX,
    gnmy_type_colour,
    load_level,
    new_game_state,
    overlay_gnmy,
    render_tiles,
)
from lomax_modern.engine.render import COLOUR_PLAYER, COLOUR_SKY
from lomax_modern.renderer import Framebuffer
from tests.fixtures.synth import (
    build_container,
    cell_payload,
    gnmy_entries_payload,
    head_payload,
    map_payload,
    nmy_payload,
    ttab_payload,
)

#: 15-bit HEAD palette word and its ``B5G6R5`` form after widening.
RED15, RED565 = 0x7C00, 0xF800


def _palette(index_colours: dict[int, int]) -> list[int]:
    """256 15-bit words; index 0 stays 0 (the transparent key colour)."""
    words = [0] * 256
    for index, word in index_colours.items():
        words[index] = word
    return words


#: A solid red 8x8 CELL: every pixel is palette index 1.
RED_CELL = bytes([1] * 64)
#: A TTAB record whose four slots all name CELL 0, no flags.
RED_TILE = [0, 0, 0, 0, 0, 0, 0, 0]


def _entry(type_index: int, x: int, y: int) -> GnmyEntry:
    """A minimal placement entry (size/params/extra irrelevant to the overlay)."""
    return GnmyEntry(
        size=10, type_index=type_index, x=x, y=y, flags=0, params=(), extra=None
    )


def _world_with_gnmy(
    width_cells: int,
    height_cells: int,
    gnmy: list[tuple[int, int, int, int, tuple[int, ...], int | None]],
    *,
    nmy_records: int = 1,
) -> bytes:
    """One plane whose MAP is a red tile, plus a decoded ``GNMY`` chunk.

    ``gnmy`` entries use the recovered layout (``type, x, y, flags, params,
    extra``); the ``NMY`` chunk supplies ``nmy_records`` records of ``K=1``
    (``W_A = 0x10``), so a ``type_index`` below ``nmy_records`` decodes.
    """
    width_units = width_cells * 2
    height_units = height_cells * 2
    map_cells = [(0, 0)] * (width_cells * height_cells)
    chunks = [
        ("WRLD", b"PS-X" + b"\0" * 4),
        ("NMY", nmy_payload([(f"T{i}", 0) for i in range(nmy_records)], trailer=2)),
        ("PARA", b"\0" * 8),
        (
            "HEAD",
            head_payload(width_units, height_units, palettes=[[0] * 256, _palette({1: RED15})]),
        ),
        ("TTAB", ttab_payload([RED_TILE])),
        ("MAP", map_payload(width_units, height_units, cells=map_cells)),
        ("GNMY", gnmy_entries_payload(gnmy)),
        ("MACR", b"\0" * 8),
        ("PAGE", b"\0" * 8),
        ("CELL", cell_payload([RED_CELL])),
        ("ANIM", b"\0" * 20),
        ("END", b""),
    ]
    return build_container(chunks, endian=">")


def _load(tmp_path: Path, data: bytes):
    path = tmp_path / "test.WLD"
    path.write_bytes(data)
    return load_level(path)


def test_gnmy_type_colour_is_deterministic_and_distinct() -> None:
    """Same index maps to the same colour; eight distinct indices differ."""
    colours = [gnmy_type_colour(i) for i in range(8)]
    assert len(set(colours)) == 8  # eight distinct hues
    assert gnmy_type_colour(0) == gnmy_type_colour(8)  # wraps by table length
    assert gnmy_type_colour(3) == gnmy_type_colour(3)


def test_overlay_gnmy_draws_one_marker_per_entry_at_its_pixel() -> None:
    """A placement paints a 3x3 marker centred on its pixel, in its type colour."""
    fb = Framebuffer(320, 240, fill=COLOUR_SKY)
    overlay_gnmy(fb, [_entry(3, 100, 50)], 0, 0)

    colour = gnmy_type_colour(3)
    assert fb.pixel(100, 50) == colour  # centre
    assert fb.pixel(99, 49) == colour  # top-left of the 3x3
    assert fb.pixel(101, 51) == colour  # bottom-right of the 3x3
    assert fb.pixel(98, 50) == COLOUR_SKY  # outside the marker
    assert fb.pixel(102, 50) == COLOUR_SKY


def test_overlay_gnmy_offsets_by_camera_and_clips() -> None:
    """Camera subtraction moves markers; off-viewport markers are not painted."""
    fb = Framebuffer(320, 240, fill=COLOUR_SKY)
    entries = [_entry(1, 150, 60), _entry(2, 500, 60)]
    overlay_gnmy(fb, entries, cam_x=100, cam_y=0)

    # (150, 60) - (100, 0) = screen (50, 60): in view.
    assert fb.pixel(50, 60) == gnmy_type_colour(1)
    # (500, 60) - (100, 0) = screen (400, 60): past the 320-px right edge.
    assert fb.pixel(400, 60) == COLOUR_SKY


def test_overlay_gnmy_does_not_attach_semantics() -> None:
    """The overlay reads only x/y/type_index; flags/params/extra never change it."""
    plain = _entry(0, 10, 10)
    decorated = GnmyEntry(
        size=14, type_index=0, x=10, y=10, flags=0x8000, params=(7, 8), extra=99
    )
    fb_a = Framebuffer(320, 240, fill=COLOUR_SKY)
    fb_b = Framebuffer(320, 240, fill=COLOUR_SKY)
    overlay_gnmy(fb_a, [plain], 0, 0)
    overlay_gnmy(fb_b, [decorated], 0, 0)
    assert fb_a.pixels == fb_b.pixels


def test_render_tiles_overlays_gnmy_markers_on_tile_art(tmp_path: Path) -> None:
    """The tile-art frame shows both the red tile art and the GNMY markers."""
    world = _world_with_gnmy(
        20,
        15,
        [
            (1, 50, 60, 0x0000, (1,), None),
            (2, 90, 120, 0x0000, (2,), None),
        ],
        nmy_records=3,
    )
    level = _load(tmp_path, world)
    assert len(level.gnmy) == 2  # both placements decoded into the level

    state = new_game_state(level, spawn_x=0.0, spawn_y=0.0)
    frame = render_tiles(level, state)

    # Tile art is present under the markers (a red tile fills the plane);
    # (30, 30) is outside the 12x14 player marker at the spawn.
    assert frame.pixel(30, 30) == RED565
    # Each placement paints its type-coloured marker on top of the red art.
    # Types 1 and 2 are green/blue, so the assertions are meaningful: they
    # prove the marker overwrote the art, not that red art happened to match.
    assert frame.pixel(50, 60) == gnmy_type_colour(1)
    assert frame.pixel(90, 120) == gnmy_type_colour(2)
    assert gnmy_type_colour(1) != gnmy_type_colour(2)
    assert gnmy_type_colour(1) != RED565
    assert gnmy_type_colour(2) != RED565
    # The player marker is still overlaid at the spawn (0, 0).
    assert frame.pixel(0, 0) == COLOUR_PLAYER


def test_render_tiles_off_viewport_gnmy_is_not_drawn(tmp_path: Path) -> None:
    """A placement beyond the camera's view leaves the frame without a marker."""
    world = _world_with_gnmy(
        40, 20, [(2, 600, 100, 0x0000, (1,), None)], nmy_records=3
    )
    level = _load(tmp_path, world)
    state = new_game_state(level, spawn_x=0.0, spawn_y=0.0)
    frame = render_tiles(level, state)

    # 600 px is past the 320-px viewport at camera x=0, so the type-2 (blue)
    # marker colour appears nowhere in the frame; the art is still red.
    assert gnmy_type_colour(2) not in frame.pixels
    assert frame.pixel(30, 30) == RED565  # art still present, outside the marker
