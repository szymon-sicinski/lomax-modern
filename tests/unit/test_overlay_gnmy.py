def test_overlay_gnmy_draws_its_role_marker_at_the_pixel() -> None:
    """A placement paints its role's marker centred on its pixel."""
    fb = Framebuffer(320, 240, fill=COLOUR_SKY)
    overlay_gnmy(fb, [_entry(1, 100, 50, "Moneybag")], 0, 0)

    style = gnmy_marker("Moneybag")
    assert fb.pixel(100, 50) == style.colour  # centre
    assert fb.pixel(99, 49) == style.colour  # inside the 3x3
    assert fb.pixel(101, 51) == style.colour
    assert fb.pixel(98, 50) == COLOUR_SKY  # outside the 3x3
    assert fb.pixel(102, 50) == COLOUR_SKY


def test_overlay_gnmy_draws_distinct_markers_for_the_three_roles() -> None:
    """One frame with all four buckets: three role colours plus grey "other"."""
    fb = Framebuffer(320, 240, fill=COLOUR_SKY)
    entries = [
        _entry(0, 40, 80, "Start"),
        _entry(1, 80, 80, "Exit"),
        _entry(2, 120, 80, "Moneybag"),
        _entry(3, 160, 80, "Spikes"),  # a known name with no evidenced role
    ]
    overlay_gnmy(fb, entries, 0, 0)

    assert fb.pixel(40, 80) == COLOUR_GNMY_START
    assert fb.pixel(80, 80) == COLOUR_GNMY_EXIT
    assert fb.pixel(120, 80) == COLOUR_GNMY_MONEYBAG
    assert fb.pixel(160, 80) == COLOUR_GNMY_OTHER
    # A 7-px Start marker reaches two pixels out; the 3-px Moneybag one does not.
    assert fb.pixel(42, 80) == COLOUR_GNMY_START
    assert fb.pixel(122, 80) == COLOUR_SKY


def test_overlay_gnmy_offsets_by_camera_and_clips() -> None:
    """Camera subtraction moves markers; off-viewport markers are not painted."""
    fb = Framebuffer(320, 240, fill=COLOUR_SKY)
    entries = [
        _entry(0, 150, 60, "Start"),
        _entry(1, 500, 60, "Exit"),  # 400 px on screen: past the right edge
    ]
    overlay_gnmy(fb, entries, cam_x=100, cam_y=0)

    assert fb.pixel(50, 60) == COLOUR_GNMY_START  # (150, 60) - (100, 0)
    assert fb.pixel(400, 60) == COLOUR_SKY


def test_overlay_gnmy_ignores_flags_params_and_extra() -> None:
    """Only x/y/name drive the marker; flags/params/extra never change it."""
    plain = _entry(0, 10, 10, "Start")
    decorated = GnmyEntry(
        size=14,
        type_index=0,
        x=10,
        y=10,
        flags=0x8000,
        params=(7, 8),
        extra=99,
        name="Start",
    )
    fb_a = Framebuffer(320, 240, fill=COLOUR_SKY)
    fb_b = Framebuffer(320, 240, fill=COLOUR_SKY)
    overlay_gnmy(fb_a, [plain], 0, 0)
    overlay_gnmy(fb_b, [decorated], 0, 0)
    assert fb_a.pixels == fb_b.pixels


