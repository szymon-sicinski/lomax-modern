def test_load_level_resolves_each_placement_name_from_the_nmy_table(
    tmp_path: Path,
) -> None:
    """``Level.gnmy`` carries the name of the record its ``type_index`` names."""
    world = _world_with_gnmy(
        20,
        15,
        [
            (0, 10, 10, 0x0000, (1,), None),
            (2, 20, 20, 0x0000, (1,), None),
            (3, 30, 30, 0x0000, (1,), None),
        ],
        nmy_names=("Start", "Pots", "Moneybag", "Henchlemming"),
    )
    level = _load(tmp_path, world)
    assert [e.name for e in level.gnmy] == ["Start", "Moneybag", "Henchlemming"]
    assert [placement_role(e.name) for e in level.gnmy] == ["start", "moneybag", "other"]


def test_render_tiles_overlays_named_gnmy_markers_on_tile_art(tmp_path: Path) -> None:
    """The tile-art frame shows the red art plus one role marker per placement."""
    world = _world_with_gnmy(
        20,
        15,
        [
            (0, 50, 60, 0x0000, (1,), None),
            (2, 90, 120, 0x0000, (1,), None),
        ],
        nmy_names=("Start", "Pots", "Moneybag"),
    )
    level = _load(tmp_path, world)
    assert len(level.gnmy) == 2

    state = new_game_state(level, spawn_x=0.0, spawn_y=0.0)
    frame = render_tiles(level, state)

    # Red tile art is present where no marker sits ((30, 30) avoids the player).
    assert frame.pixel(30, 30) == RED565
    # Each placement paints its name's marker on top of the red art; the role
    # colours differ from each other and from the art, so this is not a match
    # by coincidence.
    assert frame.pixel(50, 60) == COLOUR_GNMY_START
    assert frame.pixel(90, 120) == COLOUR_GNMY_MONEYBAG
    assert COLOUR_GNMY_START != COLOUR_GNMY_MONEYBAG
    assert COLOUR_GNMY_START != RED565
    assert COLOUR_GNMY_MONEYBAG != RED565
    # The player marker is still overlaid at the spawn (0, 0).
    assert frame.pixel(0, 0) == COLOUR_PLAYER


def test_render_tiles_off_viewport_gnmy_is_not_drawn(tmp_path: Path) -> None:
    """A placement beyond the camera's view leaves the frame without a marker."""
    world = _world_with_gnmy(
        40,
        20,
        [(1, 600, 100, 0x0000, (1,), None)],
        nmy_names=("Pots", "Exit"),
    )
    level = _load(tmp_path, world)
    state = new_game_state(level, spawn_x=0.0, spawn_y=0.0)
    frame = render_tiles(level, state)

    # 600 px is past the 320-px viewport at camera x=0, so no green exit marker
    # appears; the red art is still there.
    assert COLOUR_GNMY_EXIT not in frame.pixels
    assert frame.pixel(30, 30) == RED565


def test_slice_report_names_the_gnmy_roles(tmp_path: Path) -> None:
    """``slice``'s console digest names Start/Exit/Moneybag and counts the rest."""
    world = _world_with_gnmy(
        20,
        15,
        [
            (0, 20, 30, 0x0000, (1,), None),  # Start
            (1, 40, 30, 0x0000, (1,), None),  # Exit
            (2, 60, 30, 0x0000, (1,), None),  # Moneybag
            (3, 80, 30, 0x0000, (1,), None),  # Spikes -> other
        ],
        nmy_names=("Start", "Exit", "Moneybag", "Spikes"),
    )
    path = tmp_path / "test.WLD"
    path.write_bytes(world)

    report, _ = run_slice(tmp_path, world_path=path, max_ticks=1)
    text = report.format()
    assert report.gnmy_roles == {"start": 1, "exit": 1, "moneybag": 1, "other": 1}
    assert "GNMY markers: 4 placements" in text
    assert "start 1" in text and "exit 1" in text
    assert "moneybag 1" in text and "other 1" in text
    assert "Start/Exit/Moneybag [V]" in text
