"""GNMY markers styled by the placement's ``NMY`` name (Q32 [V]).

``engine.overlay_gnmy`` draws one marker per ``GNMY`` placement at its pixel
``(x, y)``, styled by the ``NMY`` record name the placement's ``type_index``
resolves to.  Q32 resolved exactly three roles in ``docs/file-formats.md`` §2.5
— ``Start`` (spawn), ``Exit`` (level exit) and ``Moneybag`` (collectable) — so
those get distinct markers and every other name is one grey "other type"
bucket.  No per-name glyph is invented for the remaining names, whose handlers
are unmapped.  Every fixture is generated by :mod:`tests.fixtures.synth` — no
game bytes.
"""

from __future__ import annotations

from pathlib import Path

from lomax_modern.anim_nmy import GnmyEntry, placement_role
from lomax_modern.engine import (
    gnmy_marker,
    load_level,
    new_game_state,
    overlay_gnmy,
    render_tiles,
    run_slice,
)
from lomax_modern.engine.render import (
    COLOUR_GNMY_EXIT,
    COLOUR_GNMY_MONEYBAG,
    COLOUR_GNMY_OTHER,
    COLOUR_GNMY_START,
    COLOUR_PLAYER,
    COLOUR_SKY,
)
from lomax_modern.renderer import Framebuffer
from tests.fixtures.synth import (
    build_container,
    cell_payload,
    gnmy_entries_payload,
    head_payload,
    map_payload,
    nmy_payload,
    ttab_payload,
)

#: 15-bit HEAD palette word and its ``B5G6R5`` form after widening.
RED15, RED565 = 0x7C00, 0xF800


def _palette(index_colours: dict[int, int]) -> list[int]:
    """256 15-bit words; index 0 stays 0 (the transparent key colour)."""
    words = [0] * 256
    for index, word in index_colours.items():
        words[index] = word
    return words


#: A solid red 8x8 CELL: every pixel is palette index 1.
RED_CELL = bytes([1] * 64)
#: A TTAB record whose four slots all name CELL 0, no flags.
RED_TILE = [0, 0, 0, 0, 0, 0, 0, 0]


def _entry(type_index: int, x: int, y: int, name: str | None = None) -> GnmyEntry:
    """A minimal placement entry carrying an already-resolved ``NMY`` name."""
    return GnmyEntry(
        size=10,
        type_index=type_index,
        x=x,
        y=y,
        flags=0,
        params=(),
        extra=None,
        name=name,
    )


def _world_with_gnmy(
    width_cells: int,
    height_cells: int,
    gnmy: list[tuple[int, int, int, int, tuple[int, ...], int | None]],
    *,
    nmy_names: tuple[str, ...] = ("Type",),
) -> bytes:
    """One plane whose MAP is a red tile, plus a decoded ``GNMY`` chunk.

    ``gnmy`` entries use the recovered layout (``type, x, y, flags, params,
    extra``); the ``NMY`` chunk supplies one record per name (``W_A = 0x10``,
    so ``K=1``), so a ``type_index`` below ``len(nmy_names)`` decodes and
    resolves to that name.
    """
    width_units = width_cells * 2
    height_units = height_cells * 2
    map_cells = [(0, 0)] * (width_cells * height_cells)
    chunks = [
        ("WRLD", b"PS-X" + b"\0" * 4),
        ("NMY", nmy_payload([(name, 0) for name in nmy_names], trailer=2)),
        ("PARA", b"\0" * 8),
        (
            "HEAD",
            head_payload(width_units, height_units, palettes=[[0] * 256, _palette({1: RED15})]),
        ),
        ("TTAB", ttab_payload([RED_TILE])),
        ("MAP", map_payload(width_units, height_units, cells=map_cells)),
        ("GNMY", gnmy_entries_payload(gnmy)),
        ("MACR", b"\0" * 8),
        ("PAGE", b"\0" * 8),
        ("CELL", cell_payload([RED_CELL])),
        ("ANIM", b"\0" * 20),
        ("END", b""),
    ]
    return build_container(chunks, endian=">")


def _load(tmp_path: Path, data: bytes):
    path = tmp_path / "test.WLD"
    path.write_bytes(data)
    return load_level(path)


