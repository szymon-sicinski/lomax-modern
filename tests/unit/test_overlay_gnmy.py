def test_known_names_map_to_distinct_markers() -> None:
    """Start/Exit/Moneybag get distinct markers; no two share a style."""
    start = gnmy_marker("Start")
    exit_ = gnmy_marker("Exit")
    moneybag = gnmy_marker("Moneybag")

    assert (start.role, exit_.role, moneybag.role) == ("start", "exit", "moneybag")
    assert (start.colour, exit_.colour, moneybag.colour) == (
        COLOUR_GNMY_START,
        COLOUR_GNMY_EXIT,
        COLOUR_GNMY_MONEYBAG,
    )
    assert len({start.colour, exit_.colour, moneybag.colour}) == 3
    # The three are distinguishable without colour, too (a greyscale capture).
    assert len({start.size, exit_.size, moneybag.size}) == 3


def test_unknown_name_falls_into_one_other_bucket() -> None:
    """Any name outside the three evidenced roles is the single "other" style.

    That includes a name the decoder saw but whose handler is unmapped, a name
    on a documented sibling type (``Finish``), and an entry whose type table
    was missing (``name=None``).
    """
    other = gnmy_marker("Spikes")
    assert other.role == "other"
    assert other.colour == COLOUR_GNMY_OTHER
    assert gnmy_marker("Finish") == other
    assert gnmy_marker("Parallax") == other
    assert gnmy_marker(None) == other
    assert other not in (gnmy_marker("Start"), gnmy_marker("Exit"), gnmy_marker("Moneybag"))
    # Only the three evidenced prefixes map; nothing per-name is invented.
    assert {placement_role("Spikes"), placement_role("Henchlemming")} == {"other"}


