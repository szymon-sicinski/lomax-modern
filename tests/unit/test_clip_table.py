"""The player's clip table: clip choice is data, not hard-coded sprite ids.

AN2 of ``docs/roadmap/46-character-animation-plan.md`` §3 replaces the
single-purpose ``load_move_poses`` with a tag-keyed table (clip tag → poses) and
a **pure** ``select_clip(player)``.  AN3b makes the ground rule the original's
(``docs/file-formats.md`` §2.6.2 a rows 34-35): standing draws ``STA1``,
``0 < |vx| <= 2.0`` draws ``WALK``, ``|vx| > 2.0`` draws ``RUN`` (strict ``>``),
at rates ``|vx|/0x700`` and ``|vx|>>11`` in 1/256 pose per tick.  The airborne
case is pinned too: the air clips arrive in AN4, and until then a moving
airborne player resolves to ``WALK`` like a grounded one.

Everything is generated by ``tests.fixtures.synth`` — no game bytes.
"""

from __future__ import annotations

import itertools
from pathlib import Path

from lomax_modern.engine import (
    Input,
    Player,
    load_clip_table,
    load_level,
    load_player_sprite,
    run_slice,
    select_clip,
)
from lomax_modern.engine.entities import WALK_SPEED
from lomax_modern.engine.level import (
    PLAYER_CLIP_TAGS,
    PLAYER_RUN_ANIM,
    PLAYER_STAND_ANIM,
    PLAYER_WALK_ANIM,
)
from lomax_modern.engine.state import (
    POSE_PHASE,
    advance_pose,
    pose_rate_px256,
)
from tests.fixtures.synth import (
    anim_frames_payload,
    anim_payload,
    main_world_with_clips,
    synthetic_world,
)

#: Palette indices the fixtures paint, so a test can name the pose it drew.
#: The ``WALK`` sprite is 6x8 = 48 pixels, the ``STA1`` sprite 4x4 = 16.
WALK_FRAME_0 = tuple([1] + [0] * 47)
WALK_FRAME_1 = tuple([2] + [0] * 47)
STAND_PIXELS = tuple([3] * 16)


def _hero_clips() -> tuple[tuple[str, tuple[tuple[int, int, int, int, int], ...]], ...]:
    """``Hero``'s two clips here: ``WALK`` (two steps) and ``STA1`` (one)."""
    return (
        # Keyframe sprite bytes are 1-based: 6 -> type_index 5, 7 -> type_index 6.
        (PLAYER_WALK_ANIM, ((6, 1, 0, 0, 0x01), (6, 2, 0, 0, 0x01))),
        (PLAYER_STAND_ANIM, ((7, 1, 0, 0, 0x01),)),
    )


def _hero_sprites() -> tuple[bytes, bytes]:
    return (
        anim_frames_payload(
            5,
            (bytes(WALK_FRAME_0), bytes(WALK_FRAME_1)),
            width=6,
            height=8,
        ),
        anim_payload(
            frame_count=1,
            packed=False,
            width=4,
            height=4,
            type_index=6,
            pixels=bytes(STAND_PIXELS),
        ),
    )


def _clip_level(tmp_path: Path):
    """A synthetic level whose sibling ``MAIN.WLD`` carries ``WALK`` and ``STA1``."""
    (tmp_path / "MAIN.WLD").write_bytes(main_world_with_clips(_hero_clips(), _hero_sprites()))
    (tmp_path / "VILLAGE.WLD").write_bytes(synthetic_world(endian=">"))
    return load_level(tmp_path / "VILLAGE.WLD")


# ---------------------------------------------------------------------------
# The loader: one table, keyed by animation tag
# ---------------------------------------------------------------------------


def test_clip_table_is_keyed_by_animation_tag(tmp_path: Path) -> None:
    """``Hero``'s clips resolve into one tag-keyed table, poses per step."""
    level = _clip_level(tmp_path)

    assert set(level.clips) == {PLAYER_STAND_ANIM, PLAYER_WALK_ANIM}
    assert [pose.step for pose in level.clips[PLAYER_WALK_ANIM]] == [1, 2]
    assert [pose.pixels.indices for pose in level.clips[PLAYER_WALK_ANIM]] == [
        WALK_FRAME_0,
        WALK_FRAME_1,
    ]
    assert [pose.step for pose in level.clips[PLAYER_STAND_ANIM]] == [1]
    assert level.clips[PLAYER_STAND_ANIM][0].pixels.indices == STAND_PIXELS


def test_clip_loader_takes_any_tag_not_a_fixed_pair(tmp_path: Path) -> None:
    """The declared tags are what is loaded; a later clip (``DUCK``) needs no code.

    The loader is keyed by tag, so AN5/AN6/AN4 add a clip by naming it, and a
    tag the file does not carry is simply absent from the table.
    """
    (tmp_path / "MAIN.WLD").write_bytes(
        main_world_with_clips(
            (
                (PLAYER_WALK_ANIM, ((6, 1, 0, 0, 0x01),)),
                ("DUCK", ((6, 1, 0, 0, 0x01),)),
            ),
            (
                anim_payload(
                    frame_count=1,
                    packed=False,
                    width=4,
                    height=4,
                    type_index=5,
                    pixels=bytes(16),
                ),
            ),
        )
    )

    default = load_clip_table(tmp_path / "MAIN.WLD")
    assert PLAYER_CLIP_TAGS == (PLAYER_STAND_ANIM, PLAYER_WALK_ANIM, PLAYER_RUN_ANIM)
    # ``STA1`` and ``RUN`` are declared but this file has no such clips: absent, not invented.
    assert set(default) == {PLAYER_WALK_ANIM}

    duck = load_clip_table(tmp_path / "MAIN.WLD", clip_tags=("DUCK",))
    assert set(duck) == {"DUCK"}
    assert [pose.step for pose in duck["DUCK"]] == [1]


def test_clip_play_order_starts_at_the_first_keyframe_not_the_lowest_step(
    tmp_path: Path,
) -> None:
    """The clip's **first keyframe** names the pose it plays first.

    Retail ``STA1`` names step 4 first (measured: its 60 keyframes begin at step
    4, and steps 1-7 all resolve), so a table left in ``step`` order would put a
    different pose at index 0 and a still player would draw the wrong frame.  The
    standing sprite is that first pose, which is why `select_clip` can say
    "``STA1``, pose 0" for standing.
    """
    frames = anim_frames_payload(
        5,
        (bytes([1]) + bytes(15), bytes([2]) + bytes(15), bytes([3]) + bytes(15)),
    )
    (tmp_path / "MAIN.WLD").write_bytes(
        main_world_with_clips(
            # File order: step 2 is the first keyframe, then 3, then 1.
            (
                (
                    PLAYER_STAND_ANIM,
                    ((6, 2, 0, 0, 0x01), (6, 3, 0, 0, 0x01), (6, 1, 0, 0, 0x01)),
                ),
            ),
            (frames,),
        )
    )

    poses = load_clip_table(tmp_path / "MAIN.WLD")[PLAYER_STAND_ANIM]

    assert [pose.step for pose in poses] == [2, 3, 1]
    # step N resolves to sprite frame N-1, so the pixels name the pose.
    assert [pose.pixels.indices[0] for pose in poses] == [2, 3, 1]
    assert load_player_sprite(tmp_path / "MAIN.WLD").indices[0] == 2


def test_clip_table_is_empty_without_a_sibling_main_world(tmp_path: Path) -> None:
    assert load_clip_table(tmp_path / "MAIN.WLD") == {}


# ---------------------------------------------------------------------------
# The selector: pure, and today's rules unchanged
# ---------------------------------------------------------------------------


def test_select_clip_standing_player_resolves_to_the_standing_clip(
    tmp_path: Path,
) -> None:
    """``vx == 0`` picks ``STA1``, and that tag resolves to a pose in the table."""
    level = _clip_level(tmp_path)

    tag, pose_index = select_clip(Player(x=48.0, y=0.0))

    assert tag == PLAYER_STAND_ANIM
    pose = level.clip_pose(tag, pose_index)
    assert pose is not None
    assert pose.pixels.indices == STAND_PIXELS


def test_select_clip_moving_player_resolves_to_the_walk_clip_pose(
    tmp_path: Path,
) -> None:
    """``|vx| == 2.0`` picks ``WALK`` in either facing; the pose is ``anim_frame``."""
    level = _clip_level(tmp_path)

    for vx in (2.0, -2.0):
        tag, pose_index = select_clip(Player(x=48.0, y=0.0, vx=vx, anim_frame=4))
        assert (tag, pose_index) == (PLAYER_WALK_ANIM, 4)
    poses = level.clips[tag]
    assert level.clip_pose(tag, pose_index) is poses[4 % len(poses)]
    # The pose index cycles over the clip rather than running off its end.
    assert level.clip_pose(tag, 0) is poses[0]
    assert level.clip_pose(tag, 1) is poses[1]
    assert level.clip_pose(tag, 2) is poses[0]


def test_select_clip_above_walk_speed_resolves_to_run() -> None:
    for vx in (2.5, -2.5):
        assert select_clip(Player(x=0.0, y=0.0, vx=vx, anim_frame=3)) == (
            PLAYER_RUN_ANIM,
            3,
        )


def test_walk_run_gate_is_strict_at_exactly_two() -> None:
    """The original's ``jg`` at 0x411F79: exactly 2.0 is ``WALK``, one ulp above ``RUN``."""
    at_two = Player(x=0.0, y=0.0, vx=0x20000 / 65536)
    above = Player(x=0.0, y=0.0, vx=0x20001 / 65536)
    assert select_clip(at_two)[0] == PLAYER_WALK_ANIM
    assert select_clip(above)[0] == PLAYER_RUN_ANIM


def test_select_clip_standing_is_stand_pose_zero_for_either_zero() -> None:
    for vx in (0.0, -0.0):
        assert select_clip(Player(x=0.0, y=0.0, vx=vx, anim_frame=5)) == (
            PLAYER_STAND_ANIM,
            0,
        )


def test_pose_rates_are_the_originals_in_256ths() -> None:
    assert WALK_SPEED == 2.0
    assert pose_rate_px256(2.0) == 73  # 0x20000 // 0x700
    assert pose_rate_px256(-2.0) == 73
    assert pose_rate_px256(2.5) == 80  # 0x28000 >> 11
    assert pose_rate_px256(0.0) == 0


def test_pose_accumulator_is_integer_and_never_drifts() -> None:
    """Rate 73: holds of 3, 4, 3, 4 ticks; 2560 ticks = 730 poses, phase back at 0."""
    player = Player(x=0.0, y=0.0, vx=2.0)
    change_ticks = []
    previous = player.anim_frame
    for tick in range(1, 2561):
        advance_pose(player, 73)
        if player.anim_frame != previous:
            change_ticks.append(tick)
            previous = player.anim_frame
    # Ticks 1-3 show pose 0 (the first advance needs 292/256), then 4, 3, 4 ...
    first_four = change_ticks[:4]
    holds = [first_four[0] - 1] + [b - a for a, b in itertools.pairwise(first_four)]
    assert holds == [3, 4, 3, 4]
    assert change_ticks[:4] == [4, 8, 11, 15]
    assert player.anim_frame == 730
    assert player.anim_phase == 0
    assert POSE_PHASE == 256


def test_select_clip_airborne_player_resolves_through_the_same_table(
    tmp_path: Path,
) -> None:
    """Airborne is not special-cased yet: ``WALK`` when moving, else ``STA1``.

    The air clips (``JMP1``/``JMP2``/``LND1``) arrive in AN4.  Until then both
    airborne cases resolve through the tag table, so AN4 changes one selector,
    not the render path.
    """
    level = _clip_level(tmp_path)

    rising = Player(x=48.0, y=0.0, vx=2.0, vy=-4.0, on_ground=False)
    falling_still = Player(x=48.0, y=0.0, vx=0.0, vy=2.0, on_ground=False)

    assert select_clip(rising)[0] == PLAYER_WALK_ANIM
    assert select_clip(falling_still)[0] == PLAYER_STAND_ANIM
    for player in (rising, falling_still):
        tag, pose_index = select_clip(player)
        assert level.clip_pose(tag, pose_index) is not None


def test_select_clip_is_pure_and_reads_only_the_player() -> None:
    """No level, no I/O, no module state: the same player picks the same clip."""
    player = Player(x=0.0, y=0.0, vx=-2.0, anim_frame=7)

    selection = select_clip(player)

    assert selection == select_clip(player)
    # Position and span of free fall do not enter the choice today.
    assert select_clip(Player(x=999.0, y=999.0, vx=-2.0, anim_frame=7)) == selection
    assert selection == (PLAYER_WALK_ANIM, 7)


# ---------------------------------------------------------------------------
# The slice report: a ``clips:`` line naming what was drawn
# ---------------------------------------------------------------------------


def test_slice_report_names_the_clips_it_drew_and_counts_every_tick(
    tmp_path: Path,
) -> None:
    """Every tick is booked to the clip the selector chose; zero-count tags are not named.

    ``RUN`` is loaded but never drawn at the engine's ground speed (2.0), so the
    ``clips:`` line omits it while ``clip_ticks`` still carries ``RUN`` at 0.
    """
    clips = _hero_clips() + ((PLAYER_RUN_ANIM, ((6, 1, 0, 0, 0x01),)),)
    (tmp_path / "MAIN.WLD").write_bytes(main_world_with_clips(clips, _hero_sprites()))
    (tmp_path / "VILLAGE.WLD").write_bytes(synthetic_world(endian=">"))

    def script(tick: int, state) -> Input:
        return Input(right=True) if tick < 4 else Input()

    report, _ = run_slice(
        tmp_path,
        worlds=("VILLAGE",),
        world_path=tmp_path / "VILLAGE.WLD",
        max_ticks=8,
        script=script,
    )

    counts = dict(report.clip_ticks)
    assert report.ticks == 8
    assert sum(counts.values()) == report.ticks  # nothing drawn outside a clip
    assert set(counts) == {PLAYER_STAND_ANIM, PLAYER_WALK_ANIM, PLAYER_RUN_ANIM}
    assert counts[PLAYER_WALK_ANIM] > 0 and counts[PLAYER_STAND_ANIM] > 0
    assert counts[PLAYER_RUN_ANIM] == 0

    line = next(
        line for line in report.format().splitlines() if line.startswith("clips: ")
    )
    assert line == (
        f"clips: {PLAYER_STAND_ANIM} {counts[PLAYER_STAND_ANIM]}, "
        f"{PLAYER_WALK_ANIM} {counts[PLAYER_WALK_ANIM]}"
    )
    assert "RUN 0" not in line


def test_slice_report_omits_the_clips_line_without_a_clip_table(tmp_path: Path) -> None:
    """A world with no sibling ``MAIN.WLD`` draws the marker: no clip to name."""
    (tmp_path / "VILLAGE.WLD").write_bytes(synthetic_world(endian=">"))

    report, _ = run_slice(
        tmp_path,
        worlds=("VILLAGE",),
        world_path=tmp_path / "VILLAGE.WLD",
        max_ticks=2,
    )

    assert report.clip_ticks == ()
    assert "clips:" not in report.format()
